import { supabase } from '../../../lib/supabase'
import { stripe } from '../../../lib/stripe'
import BuyButton from './BuyButton'

export const dynamic = 'force-dynamic'

export default async function ProductPage({
  params,
  searchParams
}: {
  params: Promise<{ slug: string }>
  searchParams: Promise<{ session_id?: string }>
}) {
  const { slug } = await params
  const { session_id } = await searchParams
  const { data: product } = await supabase
    .from('products')
    .select('*')
    .eq('slug', slug)
    .eq('status', 'published')
    .maybeSingle()
  if (!product) return <main className="p-8">This product is no longer available.</main>

  // The deliverable is shown only for a paid checkout session belonging to this product
  let paid = false
  if (session_id) {
    try {
      const session = await stripe.checkout.sessions.retrieve(session_id)
      paid = session.payment_status === 'paid' && session.metadata?.product_id === product.id
    } catch {
      paid = false
    }
  }

  return (
    <main className="max-w-2xl mx-auto p-8 space-y-6">
      <h1 className="text-3xl font-bold">{product.title}</h1>
      <p className="text-gray-700">{product.description}</p>
      <p className="text-sm text-gray-500">
        This product is generated by AI and reviewed automatically. It is general information, not professional advice.
      </p>
      {paid ? (
        <article className="whitespace-pre-wrap border rounded p-4 bg-white">{product.deliverable}</article>
      ) : (
        <BuyButton slug={product.slug} label={`Buy for ${(product.price_cents / 100).toFixed(2)} ${product.currency.toUpperCase()}`} />
      )}
    </main>
  )
}
